export function baseSkillValue(name: string): number {
  const direct = SKILL_LIST.find((s) => s.name === name);
  if (direct) return direct.base;
  const colonIndex = name.indexOf(":");
  const category = (colonIndex === -1 ? name : name.slice(0, colonIndex)).trim();
  const variant = VARIANT_SKILLS.find((v) => v.category === category);
  return variant?.base ?? 0;
}

